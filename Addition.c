#include <stdio.h> // Allows the program to use input/output functions, especially printf(). 

int main() { // This is the main function. It is where the program starts running. 

    int num1 = 12; // Stores the first number, 12.
    int num2 = 8; // Stores the second number, 8.
    int sum; // It will stores the result of adding the two numbers. 

    sum = num1 + num2; // Adds num1 and num2 together and stores the result in sum. 

    printf("First number: %d\n", num1); // Displays the value of num1. 
    printf("Second number : %d\n", num2); // Displays the value of num2. 
    printf("Sum: %d\n", sum); // Displays the caluculated sum. 

    return 0; // Ends the program and indicates that it ran successfully. 
}
